import fs from 'node:fs';
import vm from 'node:vm';
import test from 'node:test';
import assert from 'node:assert/strict';

const source=fs.readFileSync(new URL('../public/profile-techniques.js',import.meta.url),'utf8');

test('drag suppression does not consume the next unrelated ability-card click',()=>{
 const start=source.indexOf('  function bindTrack(track) {');
 const end=source.indexOf('  function decorate() {',start);
 assert(start>=0&&end>start);
 const listeners=new Map(),opened=[];
 const track={
  dataset:{},style:{},scrollLeft:0,
  classList:{add(){},remove(){}},
  addEventListener:(event,callback)=>listeners.set(event,callback)
 };
 const context={openCard:id=>opened.push(id),getComputedStyle:()=>({columnGap:'0'})};
 const bindTrack=vm.runInNewContext(source.slice(start,end)+';bindTrack',context);
 bindTrack(track);
 const down=x=>listeners.get('pointerdown')({button:0,pointerType:'mouse',pointerId:1,clientX:x});
 const move=x=>listeners.get('pointermove')({pointerId:1,clientX:x});
 const up=()=>listeners.get('pointerup')({pointerId:1});
 const click=()=>listeners.get('click')({target:{closest:()=>({dataset:{openAbility:'ability-1'}})}});
 down(100);move(65);up();
 assert.equal(track.dataset.preventCardClick,'true');
 // Some browsers do not deliver a click after releasing a dragged track.
 down(100);up();click();
 assert.deepEqual(opened,['ability-1'],'a later independent click must open its card');

 down(100);move(60);up();click();
 assert.deepEqual(opened,['ability-1'],'the click generated by a drag must still be suppressed');
});

test('ability registry cache refreshes when the data payload is replaced',()=>{
 const context={data:{abilities:[{id:'sample',name:'Original'}]},esc:value=>String(value)};
 const techniques=vm.runInNewContext(source+';ProfileTechniques',context);
 assert(techniques.card({id:'sample'},0).includes('Original'));
 context.data={abilities:[{id:'sample',name:'Updated'}]};
 const result=techniques.card({id:'sample'},0);
 assert(result.includes('Updated'));
 assert(!result.includes('Original'));
});
